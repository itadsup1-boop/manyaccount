-- Nguồn Facebook Group được lưu độc lập với nguồn Page cũ.
-- Không ALTER và không di chuyển dữ liệu trong public.facebook_sources.
-- Safe to run more than once in Supabase SQL Editor.

create table if not exists public.facebook_group_sources (
    id bigint generated by default as identity primary key,
    id_tiktok text not null default 'Adsupnews',
    source_name text not null,
    source_url text not null unique,
    edit_mode text not null default 'hook_then_original',
    max_video_age_hours integer not null default 48,
    max_videos_per_scan integer not null default 5,
    scan_interval_min integer not null default 30,
    delogo text not null default '',
    platform text not null default 'facebook_group',
    is_active boolean not null default true,
    extra_content text not null default '',
    last_video_id text,
    last_scan_at timestamptz,
    created_at timestamptz not null default now(),
    constraint facebook_group_sources_url_check
        check (source_url ~* 'facebook\.com/groups/'),
    constraint facebook_group_sources_edit_mode_check
        check (edit_mode in ('full_ai_voiceover', 'hook_then_original')),
    constraint facebook_group_sources_max_age_check
        check (max_video_age_hours between 0 and 720),
    constraint facebook_group_sources_max_videos_check
        check (max_videos_per_scan between 1 and 10)
);

create table if not exists public.facebook_group_videos (
    id uuid primary key default gen_random_uuid(),
    source_id bigint not null
        references public.facebook_group_sources(id) on delete cascade,
    facebook_video_id text not null,
    original_url text not null,
    caption text not null default '',
    status text not null default 'pending',
    file_hash text,
    file_size_bytes bigint,
    downloaded_path text,
    ai_title text,
    ai_script text,
    processed_path text,
    review_video_path text,
    review_payload jsonb not null default '{}'::jsonb,
    review_error text not null default '',
    drive_link text,
    sheet_row bigint,
    reviewed_at timestamptz,
    created_at timestamptz not null default now(),
    constraint facebook_group_videos_source_video_unique
        unique (source_id, facebook_video_id)
);

alter table if exists public.facebook_group_videos
    add column if not exists review_video_path text;
alter table if exists public.facebook_group_videos
    add column if not exists review_payload jsonb not null default '{}'::jsonb;
alter table if exists public.facebook_group_videos
    add column if not exists review_error text not null default '';
alter table if exists public.facebook_group_videos
    add column if not exists drive_link text;
alter table if exists public.facebook_group_videos
    add column if not exists sheet_row bigint;
alter table if exists public.facebook_group_videos
    add column if not exists reviewed_at timestamptz;

create index if not exists facebook_group_sources_active_created_idx
    on public.facebook_group_sources (is_active, created_at);

create index if not exists facebook_group_videos_hash_idx
    on public.facebook_group_videos (file_hash);
